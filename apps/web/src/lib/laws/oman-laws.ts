export function getLawBySlug(slug: string) {
  return OMAN_LAWS.find((law) => law.slug === slug) ?? null;
}

export function listLawCategories(locale: "ar" | "en" = "ar") {
  const key = locale === "ar" ? "categoryAr" : "categoryEn";
  return [...new Set(OMAN_LAWS.map((law) => law[key]))];
}
