export function recordLabel(value: unknown, locale: "ar" | "en") {
  const key = String(value ?? "");
  return locale === "ar"
    ? (ar[key] ?? key)
    : key.replaceAll("_", " ").replaceAll(".", " ").toLowerCase();
}
